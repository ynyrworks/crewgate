'use strict';

// Writes docs/CONFIG.md from the config schema (plugins/crewgate/lib/core/config.js).
// Usage: node scripts/gen-config-docs.js [--check]   (--check exits 1 when the file is stale)
const fs = require('fs');
const path = require('path');
const config = require('../plugins/crewgate/lib/core/config');

const OUT = path.join(__dirname, '..', 'docs', 'CONFIG.md');

const cell = (s) => String(s).replace(/\|/g, '\|').replace(/\r?\n/g, ' ');
const code = (v) => `\`${cell(JSON.stringify(v))}\``;

function constraint(e) {
  const parts = [e.type === 'array' && e.itemType ? `array of ${e.itemType}` : e.type];
  if (e.enum) parts.push(`one of ${e.enum.map((x) => `\`${x}\``).join(', ')}`);
  if (e.min !== undefined) parts.push(`min ${e.min}`);
  if (e.max !== undefined) parts.push(`max ${e.max}`);
  return parts.join('; ');
}

function table(schema) {
  const rows = ['| Key | Type and limits | Default | Description | 說明 |', '|---|---|---|---|---|'];
  for (const e of schema) {
    const def = e.default === undefined ? '' : code(e.default);
    rows.push(`| \`${cell(e.path)}\` | ${cell(constraint(e))} | ${def} | ${cell(e.description.en)} | ${cell(e.description['zh-TW'])} |`);
  }
  return rows.join('\n');
}

function render() {
  return [
    '# Configuration reference',
    '',
    '<!-- Generated by scripts/gen-config-docs.js from the config schema. Do not edit by hand. -->',
    '',
    'Every key is optional. Unknown keys are kept as they are. A `*` in a key stands for any name',
    '(for example `roles.*.model` covers `roles.worker.model`, `roles.docs-writer.model`, ...).',
    'The board\'s Settings page edits the same files and validates against the same schema.',
    '',
    '## Project config: `<repo>/.claude/crew.json`',
    '',
    'Committed with the project. Created by `crew init`.',
    '',
    table(config.SCHEMA),
    '',
    '## Global config: `~/.crewgate/config.json`',
    '',
    'Per user (override the folder with `CREWGATE_HOME`). Not part of any repository.',
    '',
    table(config.GLOBAL_SCHEMA),
    '',
  ].join('\n');
}

module.exports = { render, OUT };

if (require.main === module) {
  const text = render();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = fs.readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (cur.replace(/\r\n/g, '\n') !== text) { process.stderr.write('docs/CONFIG.md is stale: run node scripts/gen-config-docs.js\n'); process.exit(1); }
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, text);
    process.stdout.write(`wrote ${path.relative(process.cwd(), OUT)}\n`);
  }
}
